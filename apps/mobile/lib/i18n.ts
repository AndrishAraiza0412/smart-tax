// Get device locale
const deviceLocale = Localization.getLocales()[0]?.languageCode ?? "es";
const supportedLocales = ["es", "en"];
const locale = supportedLocales.includes(deviceLocale) ? deviceLocale : "es";

i18n.locale = locale;

export { i18n, locale };

// Type-safe translation keys
export type TranslationKeys = typeof translations.es;

// Helper to get nested translation with interpolation
export function t(key: string, options?: Record<string, string | number>): string {
  return i18n.t(key, options);
}
